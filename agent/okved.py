_word = re.compile(r"[a-zа-яё0-9-]+", re.I)


def _stems(text: str) -> list[str]:
    return [w.lower().replace("ё", "е") for w in _word.findall(text or "") if len(w) > 2]


def search_okved(query: str, limit: int = 5) -> list[dict]:
    """Ранжирует коды по совпадению основ слов запроса с ключевыми словами и названием."""
    q = _stems(query)
    if not q:
        return []
    scored = []
    for code, title, kw, npd, psn, lic in OKVED:
        kw_list = kw.lower().replace("ё", "е").split()
        title_l = title.lower().replace("ё", "е")
        score = 0.0
        for w in q:
            for k in kw_list:
                weight = 4.0 if k.startswith("!") else 2.0
                k = k.lstrip("!")
                if len(k) < 3:
                    continue
                if len(k) == 3:
                    hit = w.startswith(k) and len(w) <= 5   # «сад», «мыло», но не «оборот» от «обо»
                else:
                    hit = w.startswith(k) or (len(w) >= 4 and k.startswith(w))
                if hit:
                    score += weight
                    break
            if len(w) >= 5 and w[:5] in title_l:
                score += 1.0
        if score > 0:
            scored.append((score, code, title, npd, psn, lic))
    scored.sort(key=lambda x: (-x[0], x[1]))
    return [
        {"code": c, "title": t, "npd_ok": n, "psn_typical": p, "license_or_special": l,
         "score": round(s, 1)}
        for s, c, t, n, p, l in scored[:limit]
    ]


def okved_title(code: str) -> str | None:
    for c, t, *_ in OKVED:
        if c == code:
            return t
    return None


def validate_okved_format(code: str) -> bool:
    """В Р21001 нужен код не короче 4 знаков: XX.XX, XX.XX.X или XX.XX.XX."""
    return bool(re.fullmatch(r"\d{2}\.\d{2}(\.\d{1,2})?", code.strip()))
