def inn_valid(inn: str) -> bool:
    """Контрольные цифры 12-значного ИНН физлица."""
    if not re.fullmatch(r"\d{12}", inn or ""):
        return False
    d = [int(c) for c in inn]
    k1 = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
    k2 = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
    c1 = sum(a * b for a, b in zip(k1, d[:10])) % 11 % 10
    c2 = sum(a * b for a, b in zip(k2, d[:11])) % 11 % 10
    return c1 == d[10] and c2 == d[11]


def precheck(applicant: dict) -> dict:
    """Предпроверка данных заявителя на ошибки, ведущие к отказу или возврату."""
    errors, warnings, ok = [], [], []
    fio = (applicant.get("fio") or "").strip()
    if len(fio.split()) < 2:
        errors.append("ФИО: укажите фамилию и имя (отчество — если есть) как в паспорте.")
    elif re.search(r"[A-Za-z]", fio) and not applicant.get("foreign"):
        errors.append("ФИО гражданина РФ указывается кириллицей, как в паспорте.")
    else:
        ok.append("ФИО заполнено")

    bd = applicant.get("birth_date")
    if bd:
        try:
            b = date.fromisoformat(bd)
            today = date.today()
            age = today.year - b.year - ((today.month, today.day) < (b.month, b.day))
            if age < 18:
                warnings.append("Вам меньше 18 лет: понадобится согласие родителей (нотариальное), "
                                "эмансипация или брак.")
            else:
                ok.append("Возраст 18+")
        except ValueError:
            errors.append("Дата рождения: используйте формат ГГГГ-ММ-ДД.")

    pas = re.sub(r"\s", "", applicant.get("passport") or "")
    if pas and not applicant.get("foreign"):
        if re.fullmatch(r"\d{10}", pas):
            ok.append("Серия и номер паспорта в правильном формате")
        else:
            errors.append("Паспорт РФ: серия — 4 цифры, номер — 6 цифр.")

    inn = (applicant.get("inn") or "").strip()
    if inn:
        if inn_valid(inn):
            ok.append("ИНН прошёл проверку контрольных цифр")
        else:
            errors.append("ИНН не проходит проверку контрольных цифр — проверьте опечатку.")

    codes = applicant.get("okved") or []
    if isinstance(codes, str):
        codes = [c.strip() for c in re.split(r"[,;\s]+", codes) if c.strip()]
    if not codes:
        errors.append("Не указан ни один код ОКВЭД — это основание для отказа.")
    for c in codes:
        if not validate_okved_format(c):
            errors.append(f"ОКВЭД {c}: нужен код не короче 4 знаков (например 62.01).")
    if codes and all(validate_okved_format(c) for c in codes):
        ok.append(f"Коды ОКВЭД в правильном формате ({len(codes)} шт.)")

    if applicant.get("already_ip"):
        errors.append("У вас уже есть действующий статус ИП — повторная регистрация невозможна.")
    if applicant.get("court_ban"):
        errors.append("Действует запрет суда на предпринимательскую деятельность — будет отказ.")
    if applicant.get("bankrupt_recent"):
        errors.append("Гражданин, признанный банкротом как ИП, не может снова зарегистрироваться "
                      "в течение 5 лет (ст. 216 127-ФЗ) — будет отказ.")

    channel = applicant.get("channel")
    if channel in ("mfc", "ifns") and applicant.get("representative"):
        warnings.append("Подача через представителя: подпись на Р21001 заверяет нотариус, нужна доверенность.")
    if not applicant.get("email"):
        warnings.append("Укажите e-mail: на него придут документы о регистрации.")

    risk = "высокий" if errors else ("средний" if warnings else "низкий")
    return {"refusal_risk": risk, "errors": errors, "warnings": warnings, "passed": ok}


def r21001_draft(applicant: dict, regime: str = "usn6") -> dict:
    """Структура данных для заполнения Р21001 (по листам формы)."""
    codes = applicant.get("okved") or []
    if isinstance(codes, str):
        codes = [c.strip() for c in re.split(r"[,;\s]+", codes) if c.strip()]
    main, extra = (codes[0], codes[1:]) if codes else (None, [])
    return {
        "Страница 1 — сведения о физлице": {
            "ФИО (рус.)": applicant.get("fio"),
            "ИНН": applicant.get("inn") or "не указывается, если нет — присвоят",
            "Пол": applicant.get("sex"),
            "Дата рождения": applicant.get("birth_date"),
            "Место рождения": applicant.get("birth_place"),
            "Гражданство": "РФ" if not applicant.get("foreign") else "иностранное",
        },
        "Страница 2 — документ, удостоверяющий личность": {
            "Вид документа": "21 (паспорт гражданина РФ)" if not applicant.get("foreign") else "по документу",
            "Серия и номер": applicant.get("passport"),
        },
        "Лист А — коды ОКВЭД": {
            "Основной вид": f"{main} — {okved_title(main) or 'проверьте название'}" if main else None,
            "Дополнительные": [f"{c} — {okved_title(c) or 'проверьте название'}" for c in extra],
        },
        "Лист Б — для налоговой": {
            "Способ выдачи документов": "на адрес электронной почты",
            "E-mail": applicant.get("email"),
            "Телефон": applicant.get("phone"),
        },
        "Сопроводительно": REGIME_STEP.get(regime, ""),
    }
